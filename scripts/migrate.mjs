import { neon } from "@neondatabase/serverless";

const databaseUrl =
  process.env.DATABASE_URL ||
  process.env.POSTGRES_URL ||
  process.env.NEON_DATABASE_URL;

if (!databaseUrl) {
  console.error(
    "Error: Please set DATABASE_URL in your environment or .env.local"
  );
  process.exit(1);
}

const sql = neon(databaseUrl);

const defaultTenants = Array.from({ length: 7 }, (_, index) => ({
  name: `Kiraydar ${index + 1}`,
  phone: "",
  base_rent: 2200,
  previous_unit: 0
}));

async function migrate() {
  console.log("Setting up database tables on Neon PostgreSQL...");

  // 1. Create tenants table
  await sql`
    CREATE TABLE IF NOT EXISTS tenants (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      phone TEXT NOT NULL DEFAULT '',
      base_rent INTEGER NOT NULL DEFAULT 2200,
      previous_unit INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `;
  console.log("✓ Table verified: tenants");

  // 2. Create bills table
  await sql`
    CREATE TABLE IF NOT EXISTS bills (
      id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      tenant_name TEXT NOT NULL,
      month TEXT NOT NULL,
      previous_unit INTEGER NOT NULL,
      current_unit INTEGER NOT NULL,
      used_unit INTEGER NOT NULL,
      unit_rate INTEGER NOT NULL,
      electricity_amount INTEGER NOT NULL,
      base_rent INTEGER NOT NULL,
      total_amount INTEGER NOT NULL,
      paid BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `;
  console.log("✓ Table verified: bills");

  // 3. Create indexes
  await sql`CREATE INDEX IF NOT EXISTS bills_tenant_id_idx ON bills(tenant_id);`;
  await sql`CREATE INDEX IF NOT EXISTS bills_month_idx ON bills(month);`;
  await sql`CREATE INDEX IF NOT EXISTS bills_created_at_idx ON bills(created_at DESC);`;
  console.log("✓ Indexes verified");

  // 4. Create owners table for private login
  await sql`
    CREATE TABLE IF NOT EXISTS owners (
      id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      email TEXT UNIQUE NOT NULL,
      password TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `;
  console.log("✓ Table verified: owners");

  // Reset data if --reset flag is passed
  if (process.argv.includes("--reset")) {
    console.log("Clearing all data (--reset)...");
    await sql`TRUNCATE TABLE bills CASCADE`;
    await sql`TRUNCATE TABLE owners CASCADE`;
    await sql`TRUNCATE TABLE tenants RESTART IDENTITY CASCADE`;
    for (const t of defaultTenants) {
      await sql`
        INSERT INTO tenants (name, phone, base_rent, previous_unit)
        VALUES (${t.name}, ${t.phone}, ${t.base_rent}, ${t.previous_unit})
      `;
    }
    console.log("✓ Data reset to default clean state (0 bills, 0 owners, 7 default tenants).");
    return;
  }

  // Seed default tenants if table is completely empty
  const existingTenants = await sql`SELECT count(*) FROM tenants`;
  const count = parseInt(existingTenants[0].count, 10);

  if (count === 0) {
    for (const t of defaultTenants) {
      await sql`
        INSERT INTO tenants (name, phone, base_rent, previous_unit)
        VALUES (${t.name}, ${t.phone}, ${t.base_rent}, ${t.previous_unit})
      `;
    }
    console.log("✓ Seeded default 7 tenants.");
  }

  console.log("Migration completed successfully!");
}

migrate().catch((err) => {
  console.error("Migration failed:", err);
  process.exit(1);
});
